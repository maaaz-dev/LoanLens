-- ==============================================================================
-- Loan Default Risk Prediction - Oracle Database XE 10g Schema
-- Target Database: Oracle Database 10g Express Edition (XE) / Oracle 10.2+
-- Purpose: Schema for storing loan application inputs and model prediction records.
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. Sequences for Primary Key Generation (Oracle 10g Compatible)
-- Note: Oracle 10g does not support IDENTITY columns (introduced in Oracle 12c).
-- ------------------------------------------------------------------------------

CREATE SEQUENCE LOAN_APPLICATION_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE PREDICTION_RECORD_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- ------------------------------------------------------------------------------
-- 2. Table: LOAN_APPLICATION
-- Stores loan applicant input features. Preserves raw categorical and numerical
-- values for transmission to the Python ML inference API.
--
-- BACKWARD COMPATIBILITY NOTE (v2.0):
-- INF_MARITAL_STATUS and INF_GENDER are legacy demographic columns made NULLABLE.
-- New applications do not collect or store these fields to protect applicant privacy.
-- For existing deployments, run the migration statements below:
--   ALTER TABLE LOAN_APPLICATION MODIFY (INF_MARITAL_STATUS NULL);
--   ALTER TABLE LOAN_APPLICATION MODIFY (INF_GENDER NULL);
-- ------------------------------------------------------------------------------

CREATE TABLE LOAN_APPLICATION (
    APPLICATION_ID         NUMBER(10)      NOT NULL,
    INVESTMENT_TOTAL       NUMBER(15, 2)   NOT NULL,
    ACCCURRENTBALANCE      NUMBER(15, 2)   NOT NULL,
    INF_MARITAL_STATUS     VARCHAR2(30)    NULL,      -- Deprecated legacy column, nullable
    INF_GENDER             VARCHAR2(10)    NULL,      -- Deprecated legacy column, nullable
    INSTALL_SIZE           NUMBER(15, 2)   NOT NULL,
    DUE_PAYMENT            NUMBER(15, 2)   NOT NULL,
    COMPENSATION_CHARGED   VARCHAR2(30)    NOT NULL,
    CLIENT_TYPE            VARCHAR2(30)    NOT NULL,
    REPAY_MODE             VARCHAR2(30)    NOT NULL,
    CREATED_AT             TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_LOAN_APPLICATION PRIMARY KEY (APPLICATION_ID)
);

-- Comments on LOAN_APPLICATION columns
COMMENT ON TABLE LOAN_APPLICATION IS 'Stores incoming loan applications and the seven active input features for ML risk scoring';
COMMENT ON COLUMN LOAN_APPLICATION.APPLICATION_ID IS 'Surrogate primary key generated by LOAN_APPLICATION_SEQ';
COMMENT ON COLUMN LOAN_APPLICATION.INVESTMENT_TOTAL IS 'Total loan/investment amount requested by the client';
COMMENT ON COLUMN LOAN_APPLICATION.ACCCURRENTBALANCE IS 'Current account balance; may be negative if overdraft is permitted';
COMMENT ON COLUMN LOAN_APPLICATION.INF_MARITAL_STATUS IS 'Legacy demographic column (deprecated in v2.0; nullable for backward compatibility)';
COMMENT ON COLUMN LOAN_APPLICATION.INF_GENDER IS 'Legacy demographic column (deprecated in v2.0; nullable for backward compatibility)';
COMMENT ON COLUMN LOAN_APPLICATION.INSTALL_SIZE IS 'Installment size amount per payment schedule';
COMMENT ON COLUMN LOAN_APPLICATION.DUE_PAYMENT IS 'Due payment amount';
COMMENT ON COLUMN LOAN_APPLICATION.COMPENSATION_CHARGED IS 'Compensation charged indicator/category preserved as text for ML pipeline';
COMMENT ON COLUMN LOAN_APPLICATION.CLIENT_TYPE IS 'Branch area category (Rural, Semi-urban, Urban) preserved as text for ML pipeline';
COMMENT ON COLUMN LOAN_APPLICATION.REPAY_MODE IS 'Repayment schedule mode (Normal, Installment) preserved as text for ML pipeline';
COMMENT ON COLUMN LOAN_APPLICATION.CREATED_AT IS 'Timestamp when the application record was created';
COMMENT ON COLUMN LOAN_APPLICATION.UPDATED_AT IS 'Timestamp when the application record was last updated';

-- ------------------------------------------------------------------------------
-- 3. Table: PREDICTION_RECORD
-- Stores ML model inference outcomes linked to a specific loan application.
-- Supports 1-to-many relationship: multiple predictions per application allow
-- model re-evaluations and comparisons without mutating original data.
-- ------------------------------------------------------------------------------

CREATE TABLE PREDICTION_RECORD (
    PREDICTION_ID          NUMBER(10)      NOT NULL,
    APPLICATION_ID         NUMBER(10)      NOT NULL,
    MODEL_VERSION          VARCHAR2(50)    NOT NULL,
    PREDICTED_CLASS        VARCHAR2(10)    NOT NULL,
    PROBABILITY_B          NUMBER(7, 6)    NOT NULL,
    THRESHOLD_USED         NUMBER(5, 4)    NOT NULL,
    PREDICTION_TIMESTAMP   TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PREDICTION_RECORD PRIMARY KEY (PREDICTION_ID),
    CONSTRAINT FK_PRED_APPLICATION FOREIGN KEY (APPLICATION_ID)
        REFERENCES LOAN_APPLICATION (APPLICATION_ID),
    CONSTRAINT CHK_PRED_CLASS CHECK (PREDICTED_CLASS IN ('G', 'B')),
    CONSTRAINT CHK_PROB_B CHECK (PROBABILITY_B >= 0.0 AND PROBABILITY_B <= 1.0),
    CONSTRAINT CHK_THRESHOLD CHECK (THRESHOLD_USED >= 0.0 AND THRESHOLD_USED <= 1.0)
);

-- Index on Foreign Key for query performance
CREATE INDEX IDX_PRED_APP_ID ON PREDICTION_RECORD (APPLICATION_ID);

-- Comments on PREDICTION_RECORD columns
COMMENT ON TABLE PREDICTION_RECORD IS 'Stores history of model inference results for loan applications';
COMMENT ON COLUMN PREDICTION_RECORD.PREDICTION_ID IS 'Surrogate primary key generated by PREDICTION_RECORD_SEQ';
COMMENT ON COLUMN PREDICTION_RECORD.APPLICATION_ID IS 'Foreign key referencing LOAN_APPLICATION(APPLICATION_ID)';
COMMENT ON COLUMN PREDICTION_RECORD.MODEL_VERSION IS 'Identifier/version of the ML model producing the prediction (e.g. lgbm_v2.0)';
COMMENT ON COLUMN PREDICTION_RECORD.PREDICTED_CLASS IS 'Predicted class label: G (Good) or B (Bad)';
COMMENT ON COLUMN PREDICTION_RECORD.PROBABILITY_B IS 'Model probability score for class B (range: 0.0 to 1.0)';
COMMENT ON COLUMN PREDICTION_RECORD.THRESHOLD_USED IS 'Decision threshold used for classification (e.g. 0.4200)';
COMMENT ON COLUMN PREDICTION_RECORD.PREDICTION_TIMESTAMP IS 'Timestamp when the model prediction was executed and recorded';
